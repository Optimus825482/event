/** K1: 15 px = 1 m. */
const PX_PER_METER = 15;
export const DIAMOND_CANVAS = { width: 960, height: 710 } as const;
export const DIAMOND_TABLE_CAPACITY = 12;

export type DiamondUnit = {
  label: string;
  x: number;
  y: number;
  capacity: number;
  isLoca: boolean;
  category: SaleCategory;
  sortNumber: number;
  size: number;
  floor: number;
};

const toCanvasX = (xm: number) => 480 + xm * PX_PER_METER;
const toCanvasY = (zm: number) => (zm + 22) * PX_PER_METER;

const STAGE_TABLE_SET = new Set<number>(DIAMOND_STAGE_TABLES);

/** 161 masa + 12 loca için Diamond salon birimlerini döner. */
export function diamondUnits(): DiamondUnit[] {
  const tables: DiamondUnit[] = DIAMOND_TABLES.map(([num, nx, nz]) => {
    const xm = nx * 28.7;
    const zm = nz * 18.9;
    const category: SaleCategory = STAGE_TABLE_SET.has(num) ? "vip" : nz < 0.28 ? "premium" : "standard";
    return {
      label: `M-${num}`,
      x: toCanvasX(xm),
      y: toCanvasY(zm),
      capacity: DIAMOND_TABLE_CAPACITY,
      isLoca: false,
      category,
      sortNumber: num,
      size: 40,
      floor: 1,
    };
  });

  const locas: DiamondUnit[] = DIAMOND_BOXES.map((box, index) => {
    const xm = (index - 5.5) * 4.97;
    const zm = 21.18;
    return {
      label: `L-${box}`,
      x: toCanvasX(xm),
      y: toCanvasY(zm),
      capacity: DIAMOND_TABLE_CAPACITY,
      isLoca: true,
      category: "vip",
      sortNumber: 1000 + index,
      size: 60,
      floor: 2,
    };
  });

  return [...tables, ...locas];
}

/** `writeLayout` girdisi olarak Diamond salon yerleşimini ve dekorunu üretir. */
export function diamondLayout(): { tables: TableInput[]; decor: DecorInput } {
  const tables: TableInput[] = diamondUnits().map((u) => ({
    label: u.label,
    capacity: u.capacity,
    tableTypeId: null,
    x: u.x,
    y: u.y,
    isLoca: u.isLoca,
    isVip: u.category === "vip",
    size: u.size,
    floor: u.floor,
    sortNumber: u.sortNumber,
  }));

  const border = { color: "#e2e8f0", width: 4 } as const;
  const bounds = { left: 30, top: 20, right: 930, bottom: 680 };

  const decor: DecorInput = {
    width: DIAMOND_CANVAS.width,
    height: DIAMOND_CANVAS.height,
    elements: [
      {
        id: "stage",
        kind: "stage",
        x: toCanvasX(-17.4 / 2),
        y: toCanvasY(-15.9 - 8.5 / 2),
        width: Math.round(17.4 * PX_PER_METER),
        height: Math.round(8.5 * PX_PER_METER),
        label: "SAHNE",
        color: "#eab308",
      },
      {
        id: "catwalk-stem",
        kind: "catwalk",
        x: toCanvasX(-2.7 / 2),
        y: toCanvasY(-7.9 - 8 / 2),
        width: 2.7 * PX_PER_METER,
        height: 8 * PX_PER_METER,
        label: "",
        color: "#65a30d",
      },
      {
        id: "catwalk-cross",
        kind: "catwalk",
        x: toCanvasX(-10.6 / 2),
        y: toCanvasY(-3.15 - 2.7 / 2),
        width: 10.6 * PX_PER_METER,
        height: 2.7 * PX_PER_METER,
        label: "",
        color: "#65a30d",
      },
    ],
    lines: [
      { id: "border-top", x1: bounds.left, y1: bounds.top, x2: bounds.right, y2: bounds.top, ...border },
      { id: "border-left", x1: bounds.left, y1: bounds.top, x2: bounds.left, y2: bounds.bottom, ...border },
      { id: "border-right", x1: bounds.right, y1: bounds.top, x2: bounds.right, y2: bounds.bottom, ...border },
      { id: "border-bottom", x1: bounds.left, y1: bounds.bottom, x2: bounds.right, y2: bounds.bottom, ...border },
    ],
  };

  return { tables, decor };
}
